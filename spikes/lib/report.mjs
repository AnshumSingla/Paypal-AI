import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = path.join(dir, ".results.json");
const mdPath = path.join(dir, "RESULTS.md");

/** Record one spike outcome and regenerate spikes/RESULTS.md. */
export function record(id, title, ok, details) {
  const all = existsSync(jsonPath) ? JSON.parse(readFileSync(jsonPath, "utf8")) : {};
  all[id] = { title, ok, details, at: new Date().toISOString() };
  writeFileSync(jsonPath, JSON.stringify(all, null, 2));

  const rows = Object.entries(all)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `| ${k} | ${v.title} | ${v.ok ? "PASS" : "FAIL"} | ${String(v.details).replace(/\|/g, "\\|").replace(/\n/g, "<br>")} | ${v.at} |`);
  writeFileSync(
    mdPath,
    `# Day-0 spike results\n\nGenerated by \`spikes/\` scripts. Sandbox only.\n\n| # | Spike | Result | Details | When |\n|---|---|---|---|---|\n${rows.join("\n")}\n`,
  );
  console.log(`\n[${ok ? "PASS" : "FAIL"}] ${id} ${title}\n${details}\n`);
}

/** Run a spike body, recording PASS on success or FAIL with the error. */
export async function spike(id, title, fn) {
  try {
    const details = await fn();
    record(id, title, true, details);
  } catch (err) {
    record(id, title, false, err?.message ?? String(err));
    process.exitCode = 1;
  }
}
